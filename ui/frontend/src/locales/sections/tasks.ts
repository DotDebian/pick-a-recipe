/**
 * Strings for the "tasks" area, keyed under the `tasks` namespace: t('tasks.someKey').
 * en is the source; fr must have exactly the same keys. Hebrew falls back to en.
 */
function pl(key: string, one: string, other: string) {
  return { [`${key}_one`]: one, [`${key}_other`]: other }
}

